export function blsEmoji(code: string): string {
  if (code.startsWith('E1')) return '🥚';
  if (code.startsWith('K7')) return '🍄';
  if (code.startsWith('M1') || code.startsWith('M2')) return '🥛';
  return GROUP_EMOJI[code[0]] ?? '🍽️';
}
